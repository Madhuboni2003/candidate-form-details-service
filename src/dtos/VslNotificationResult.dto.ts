
import { z } from 'zod';

/**
 * Validates terminal VSL notification results received from the notification service.
 * Both services must use the same field names and status values.
 */
export const vslNotificationResultSchema = z.object({
    vslRunId: z.number().int().positive(),
    vslStepId: z.number().int().positive(),

    // Public UUID of the candidate submission.
    submissionId: z.string().uuid(),

    // SENT means the provider accepted the send request.
    status: z.enum(['SENT', 'FAILED']),

    // A failure result must include a useful error message.
    errorMessage: z.string().trim().min(1).max(500).optional(),

    // ISO timestamp generated by the notification service.
    occurredAt: z.string().datetime()
}).superRefine((result, ctx) => {
    if (result.status === 'FAILED' && !result.errorMessage) {
        ctx.addIssue({
            code: z.ZodIssueCode.custom,
            path: ['errorMessage'],
            message: 'An error message is required for a failed VSL notification'
        });
    }
});

export type VslNotificationResultDto =
    z.infer<typeof vslNotificationResultSchema>;
